// npm run build:probe: compiles contracts/SimulationProbe.sol and writes src/probe-code.ts (runtime bytecode and
// ABI). test/simulation-probe.test.ts recompiles it and fails if the committed bytecode doesn't match the source.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = new URL('..', import.meta.url).pathname;
export const SETTINGS = { evmVersion: 'paris', optimizer: { enabled: true, runs: 200 }, metadata: { appendCBOR: false } } as const;

/** Compiles the probe with the pinned solc; returns the runtime bytecode and ABI. */
export function compileProbe(): { version: string; runtime: `0x${string}`; abi: unknown[] } {
  const solc = require('solc');
  const input = { language: 'Solidity', sources: { 'SimulationProbe.sol': { content: readFileSync(`${root}contracts/SimulationProbe.sol`, 'utf8') } },
    settings: { ...SETTINGS, outputSelection: { '*': { SimulationProbe: ['abi', 'evm.deployedBytecode.object'] } } } };
  const out = JSON.parse(solc.compile(JSON.stringify(input)));
  const errors = (out.errors ?? []).filter((e: { severity: string }) => e.severity === 'error');
  if (errors.length) throw new Error(errors.map((e: { formattedMessage: string }) => e.formattedMessage).join('\n'));
  const c = out.contracts['SimulationProbe.sol'].SimulationProbe;
  return { version: solc.version(), runtime: `0x${c.evm.deployedBytecode.object}`, abi: c.abi };
}

export function probeModule(p = compileProbe()): string {
  const abi = (p.abi as { type: string; name?: string }[]).filter(x => x.type === 'function' && (x.name === 'run' || x.name === 'isValidSignature'));
  return `// Generated by \`npm run build:probe\` from contracts/SimulationProbe.sol with solc ${p.version.split('+')[0]}
// (${SETTINGS.evmVersion}, optimizer ${SETTINGS.optimizer.runs} runs, no metadata). Do not edit.

/** Runtime code of SimulationProbe, set at the sending account by an eth_call state override. */
export const SIMULATION_PROBE_CODE = '${p.runtime}';

export const SIMULATION_PROBE_ABI = ${JSON.stringify(abi, null, 2)} as const;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const p = compileProbe();
  writeFileSync(`${root}src/probe-code.ts`, probeModule(p));
  console.log(`src/probe-code.ts: ${(p.runtime.length - 2) / 2} bytes of runtime code (solc ${p.version})`);
}
