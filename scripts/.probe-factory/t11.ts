import { onNode, locally, show, create, assetParams, tokenAt, SENDER, FACTORY, blockNumber } from './lib.ts';
const block = await blockNumber() - 2n;
const s = (b: string) => `0x${b.repeat(32)}` as `0x${string}`;
const salt = s('5c');
const T = tokenAt(0, SENDER, salt);
const data = create(0, salt, assetParams('Name', 'SYM'));
const [tr] = await locally([{ to: FACTORY, data, gas: 500_000n }], block, true);
const ch = tr.stateChanges!.find(c => c.address === T)!;
console.log(JSON.stringify(tr.stateChanges, (k, v) => typeof v === 'bigint' ? v.toString() : v).slice(0, 1200));
const slots = ch.storage!.map(x => x.slot.length === 66 ? x.slot : `0x${x.slot.slice(2).padStart(64, '0')}`);
const txs = [{ to: FACTORY, data, gas: 500_000n, accessList: [{ address: T, storageKeys: slots }] }, { to: FACTORY, data: create(0, s('5d'), assetParams('Name', 'SYM')), gas: 500_000n, accessList: [{ address: tokenAt(0, SENDER, s('5d')), storageKeys: [] }] }];
show('access list with slots', await onNode(txs, block), await locally(txs, block));
